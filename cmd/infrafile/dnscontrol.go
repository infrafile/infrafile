package main

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/infrafile/infrafile/internal/ledger"
	"github.com/spf13/cobra"
)

func newDNSControlCmd(opts *globalOpts) *cobra.Command {
	return &cobra.Command{Use: "dnscontrol [目录]", Short: "从 Domain 的显式 DNS 记录生成 DNSControl 配置", Args: maxArgs(1), RunE: func(cmd *cobra.Command, args []string) error {
		repo, err := loadQueryRepo(dirArg(args))
		if err != nil {
			return err
		}
		config, domains, err := renderDNSControl(repo)
		if err != nil {
			return err
		}
		if opts.json {
			return writeJSON(cmd.OutOrStdout(), struct {
				Version string   `json:"version"`
				Config  string   `json:"config"`
				Domains []string `json:"domains"`
			}{jsonVersion, config, domains})
		}
		_, err = fmt.Fprint(cmd.OutOrStdout(), config)
		return err
	}}
}

func jsString(value any) string { data, _ := json.Marshal(value); return string(data) }

func renderDNSControl(repo *ledger.Repo) (string, []string, error) {
	domains := []string{}
	records := append([]*ledger.Record(nil), repo.Records...)
	sort.Slice(records, func(i, j int) bool { return records[i].Name < records[j].Name })
	var out strings.Builder
	out.WriteString("// Generated by infrafile. Review with dnscontrol check / preview before push.\nvar REG_NONE = NewRegistrar(\"none\");\n")
	providers := map[string]int{}
	for _, r := range records {
		if r.Kind != "Domain" || r.Archived() {
			continue
		}
		spec := r.Value.(map[string]any)["spec"].(map[string]any)
		dns, ok := spec["dns"].(map[string]any)
		if !ok {
			continue
		}
		// Domain 主键允许通用资产字符，生成 DNS 时再要求合法的 zone 名。
		if !dnsZoneName(r.Name) {
			return "", nil, fmt.Errorf("Domain/%s 不是合法 DNS zone 名", r.Name)
		}
		provider := dns["provider"].(string)
		if _, ok := providers[provider]; !ok {
			fmt.Fprintf(&out, "var DSP_%d = NewDnsProvider(%s);\n", len(providers), jsString(provider))
			providers[provider] = len(providers)
		}
	}
	for _, r := range records {
		if r.Kind != "Domain" || r.Archived() {
			continue
		}
		spec := r.Value.(map[string]any)["spec"].(map[string]any)
		dns, ok := spec["dns"].(map[string]any)
		if !ok {
			continue
		}
		provider := dns["provider"].(string)
		index := providers[provider]
		fmt.Fprintf(&out, "\nD(%s, REG_NONE, DnsProvider(DSP_%d), NO_PURGE", jsString(r.Name), index)
		lines := []string{}
		owners := map[string][]string{}
		seen := map[string]bool{}
		for _, item := range dns["records"].([]any) {
			record := item.(map[string]any)
			name := strings.ToLower(record["name"].(string))
			typ := record["type"].(string)
			content := record["content"].(string)
			if len(name+"."+r.Name) > 253 {
				return "", nil, fmt.Errorf("Domain/%s DNS 记录名过长", r.Name)
			}
			for _, label := range strings.Split(name, ".") {
				if len(label) > 63 {
					return "", nil, fmt.Errorf("Domain/%s DNS 标签过长", r.Name)
				}
			}
			for _, old := range owners[name] {
				if old == "CNAME" || typ == "CNAME" {
					return "", nil, fmt.Errorf("Domain/%s 的 %s 存在 CNAME 冲突", r.Name, name)
				}
			}
			owners[name] = append(owners[name], typ)
			params := []string{jsString(name)}
			switch typ {
			case "CNAME", "MX", "NS":
				content = strings.TrimSuffix(strings.ToLower(content), ".") + "."
			}
			if typ == "MX" {
				params = append(params, fmt.Sprint(record["priority"]))
			}
			if typ == "CAA" {
				params = append(params, jsString(record["tag"]))
			}
			params = append(params, jsString(content))
			identity := typ + "(" + strings.Join(params, ", ") + ")"
			if seen[identity] {
				return "", nil, fmt.Errorf("Domain/%s 存在重复 DNS 记录", r.Name)
			}
			seen[identity] = true
			if ttl, ok := record["ttl"]; ok {
				params = append(params, fmt.Sprintf("TTL(%v)", ttl))
			}
			if proxied, ok := record["proxied"].(bool); ok {
				if proxied {
					params = append(params, "CF_PROXY_ON")
				} else {
					params = append(params, "CF_PROXY_OFF")
				}
			}
			lines = append(lines, typ+"("+strings.Join(params, ", ")+")")
		}
		sort.Strings(lines)
		for _, line := range lines {
			out.WriteString(",\n  " + line)
		}
		out.WriteString("\n);\n")
		domains = append(domains, r.Name)
	}
	return out.String(), domains, nil
}

func dnsZoneName(name string) bool {
	if len(name) > 253 || !strings.Contains(name, ".") {
		return false
	}
	for _, label := range strings.Split(name, ".") {
		if len(label) == 0 || len(label) > 63 || label[0] == '-' || label[len(label)-1] == '-' {
			return false
		}
		for _, c := range label {
			if !(c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '-') {
				return false
			}
		}
	}
	return true
}
